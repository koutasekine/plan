        await inp.fill('3'); await inp.press('Enter'); await pg.wait_for_timeout(100)
        t = await pg.input_value('#src')
        check('データベーススキーム設計 for: スキーマ days: 3 by: 上田' in t, '日数をパネルで書き換えるとテキストが変わる')
        check(await same() is True, '日数の書き換えの直後、図がテキストと一致')
        await undo_all(); check(await pg.input_value('#src') == orig, '日数の書き換えを Ctrl+Z で戻せる')
        check(await same() is True, 'Ctrl+Z の後、図がテキストと一致')
